// Helper to generate seat layout inventory for a show
export function generateSeatInventory(theatreLayout: any, bookedSeatCodes: string[] = [], blockedSeatCodes: string[] = []) {
  const rows = ['A', 'B', 'C', 'D', 'E', 'F'];
  const seatsPerRow = 10;
  const inventory: any[] = [];

  rows.forEach((rowLetter) => {
    let tier = 'Gold';
    let price = 16;
    if (rowLetter === 'A' || rowLetter === 'B') {
      tier = 'Silver';
      price = 12;
    } else if (rowLetter === 'C' || rowLetter === 'D') {
      tier = 'Gold';
      price = 16;
    } else if (rowLetter === 'E' || rowLetter === 'F') {
      tier = 'Platinum';
      price = 22;
    }

    for (let c = 1; c <= seatsPerRow; c++) {
      const seatNumber = `${rowLetter}${c}`;
      let status: 'available' | 'booked' | 'blocked' = 'available';

      if (bookedSeatCodes.includes(seatNumber)) {
        status = 'booked';
      } else if (blockedSeatCodes.includes(seatNumber)) {
        status = 'blocked';
      }

      inventory.push({
        seatNumber,
        row: rowLetter,
        col: c,
        tier,
        price,
        status,
      });
    }
  });

  return inventory;
}
